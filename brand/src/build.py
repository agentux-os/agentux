"""Build the AgentUX brand assets from code.

Everything in brand/svg, brand/png and brand/art is generated by this script:
the mark is the penguin traced from the original art (penguin.svg, see
trace.py), the wordmark is Martian Mono converted to outlines, so
none of the SVGs depends on an installed font.

Requirements (only to regenerate; the outputs are committed):
  pip install fonttools pillow
  npm install @resvg/resvg-js         (in this directory, for SVG -> PNG)
  Martian Mono variable font (OFL), e.g.
  https://raw.githubusercontent.com/google/fonts/main/ofl/martianmono/MartianMono%5Bwdth%2Cwght%5D.ttf
  saved as brand/src/MartianMono.ttf (not committed)

Usage: python brand/src/build.py
"""

import math
import os
import random
import subprocess
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SRC = Path(__file__).resolve().parent
BRAND = SRC.parent
FONT = SRC / "MartianMono.ttf"

# ---- palette -----------------------------------------------------------------
LIME = "#c6f36b"      # Signal: the accent, cockpit --accent, Plasma AccentColor
INK = "#0b0d10"       # Ink: cockpit --bg, Plymouth background
GRAPHITE = "#171b20"  # Graphite: cockpit --surface-2, raised dark surfaces
MIST = "#e7eaef"      # Mist: cockpit --text, text on Ink
MOSS = "#4f7d0b"      # Moss: the accent on light backgrounds (cockpit light --accent)
PAPER = "#f4f5f7"     # Paper: cockpit light --bg
SLATE = "#949dab"     # Slate: secondary text on Ink (cockpit --text-muted)
SLATE_L = "#5a6370"   # secondary text on Paper (cockpit light --text-muted)

SVG_NS = 'xmlns="http://www.w3.org/2000/svg"'


# ---- the mark ----------------------------------------------------------------
# A penguin swimming, its wake drawn as water lines and bubbles. The geometry is
# penguin.svg, traced from the original art (penguin.png) by trace.py, in the
# art's pixel coordinates. The penguin is drawn in full colour and the wake in
# the same colour at WAKE opacity; the middle water line is one shape with the
# penguin's back, so a gradient mask carries it from wake to body (x RAMP).
WAKE = 0.42
RAMP = (560.0, 700.0)
WING = (560.0, 380.0, 960.0, 544.0)          # keeps the wing out of the ramp
TAIL_CUT = ((610.0, 630.0), (700.0, 520.0))  # compact mark: the tail ends on this line


def _load_penguin():
    import re
    text = (SRC / "penguin.svg").read_text(encoding="utf-8")
    parts = {}
    for m in re.finditer(r'<path id="([^"]+)" data-box="([^"]+)" d="([^"]+)"/>', text):
        parts[m.group(1)] = (m.group(3), tuple(float(v) for v in m.group(2).split()))
    return parts


PENGUIN = _load_penguin()
WAKE_PARTS = [k for k in PENGUIN if k.startswith(("water-", "bubble-"))]


def _union(keys):
    boxes = [PENGUIN[k][1] for k in keys]
    return (min(b[0] for b in boxes), min(b[1] for b in boxes),
            max(b[2] for b in boxes), max(b[3] for b in boxes))


FULL_BOX = _union(PENGUIN)
COMPACT_BOX = (PENGUIN["flipper"][1][0], FULL_BOX[1], FULL_BOX[2], FULL_BOX[3])


def _d(*keys):
    return "".join(f'<path d="{PENGUIN[k][0]}"/>' for k in keys)


def mark_paths(color, uid="m", wake=WAKE):
    """The full mark, in art coordinates (FULL_BOX)."""
    x0, x1 = RAMP
    wx0, wy0, wx1, wy1 = WING
    return (
        f'<defs><linearGradient id="{uid}g" gradientUnits="userSpaceOnUse" x1="{x0:g}" y1="0" x2="{x1:g}" y2="0">'
        f'<stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff"/></linearGradient>'
        f'<mask id="{uid}k" maskUnits="userSpaceOnUse" x="0" y="0" width="1300" height="1300">'
        f'<rect width="1300" height="1300" fill="url(#{uid}g)"/>'
        f'<rect x="{wx0:g}" y="{wy0:g}" width="{wx1 - wx0:g}" height="{wy1 - wy0:g}" fill="#fff"/></mask></defs>'
        f'<g fill="{color}">'
        f'<g fill-opacity="{wake:g}">{_d(*WAKE_PARTS, "body")}</g>'
        f'<g mask="url(#{uid}k)">{_d("body")}</g>'
        f'{_d("belly", "flipper", "eye")}</g>'
    )


def compact_paths(color, uid="c"):
    """The penguin alone, for small sizes, in art coordinates (COMPACT_BOX)."""
    (ax, ay), (bx, by) = TAIL_CUT
    k = (bx - ax) / (by - ay)
    wx0, wy0, wx1, wy1 = WING
    poly = f"{ax - ay * k:.1f},0 1300,0 1300,1300 {ax + (1300 - ay) * k:.1f},1300"
    return (
        f'<defs><clipPath id="{uid}t"><polygon points="{poly}"/>'
        f'<rect x="{wx0:g}" y="{wy0:g}" width="{wx1 - wx0:g}" height="{wy1 - wy0:g}"/></clipPath></defs>'
        f'<g fill="{color}"><g clip-path="url(#{uid}t)">{_d("body")}</g>{_d("belly", "flipper", "eye")}</g>'
    )


def place(body, box, x, y, w, h, opacity=None):
    """Fit `body` (art coordinates, bounds `box`) into the rect x, y, w, h, centred."""
    bw, bh = box[2] - box[0], box[3] - box[1]
    s = min(w / bw, h / bh)
    tx = x + (w - bw * s) / 2 - box[0] * s
    ty = y + (h - bh * s) / 2 - box[1] * s
    op = f' opacity="{opacity:g}"' if opacity is not None else ""
    return f'<g transform="translate({tx:.3f} {ty:.3f}) scale({s:.5f})"{op}>{body}</g>'


def box_size(box):
    return box[2] - box[0], box[3] - box[1]


def tile(fg=LIME, bg=INK, rx=13.5, fill=0.80, inset=3.0, uid="c"):
    """Rounded tile with the compact mark, on the 64 grid (app icon). `inset` leaves a
    transparent margin, as desktop icon themes do."""
    size = 64 - 2 * inset
    m = size * (1 - fill) / 2
    return (
        f'<rect x="{inset:g}" y="{inset:g}" width="{size:g}" height="{size:g}" rx="{rx}" fill="{bg}"/>'
        + place(compact_paths(fg, uid), COMPACT_BOX, inset + m, inset + m, size - 2 * m, size - 2 * m)
    )


# ---- type ----------------------------------------------------------------------
_fonts = {}


def font(wght, wdth=100):
    key = (wght, wdth)
    if key not in _fonts:
        if not FONT.exists():
            sys.exit(f"missing {FONT}; see the docstring")
        f = TTFont(FONT)
        _fonts[key] = instantiateVariableFont(f, {"wght": wght, "wdth": wdth}, inplace=False)
    return _fonts[key]


def text_path(text, size, wght=700, wdth=100, tracking=0.0):
    """Outline text. Baseline at y=0 (y down). Returns d, advance, bounds, cap height."""
    f = font(wght, wdth)
    gs = f.getGlyphSet()
    cmap = f.getBestCmap()
    upm = f["head"].unitsPerEm
    s = size / upm
    x = 0.0
    pen = SVGPathPen(gs)
    bp = BoundsPen(gs)
    for i, ch in enumerate(text):
        g = gs[cmap[ord(ch)]]
        t = (s, 0, 0, -s, x, 0)
        g.draw(TransformPen(pen, t))
        g.draw(TransformPen(bp, t))
        x += g.width * s + (tracking * size if i + 1 < len(text) else 0)
    cap = f["OS/2"].sCapHeight * s
    return pen.getCommands(), x, bp.bounds, cap


WORD = dict(wght=720, wdth=100, tracking=-0.035)


def wordmark(size, color):
    d, adv, b, cap = text_path("AgentUX", size, **WORD)
    return f'<path fill="{color}" d="{d}"/>', adv, b, cap


def lockup(mark_color, word_color, cap_target=100.0, uid="l"):
    """Horizontal lockup. Returns (inner svg, width, height); origin top-left."""
    # Size the type so its cap height is cap_target.
    _, _, _, cap1 = text_path("A", 100, wght=WORD["wght"], wdth=WORD["wdth"])
    size = 100 * cap_target / cap1
    word, adv, b, cap = wordmark(size, word_color)
    # The mark is long and low: its height is 1.9 x the cap height.
    bw, bh = box_size(FULL_BOX)
    mh = cap * 1.9
    mw = mh * bw / bh
    gap = cap * 0.55
    baseline = mh / 2 + cap / 2          # caps centred on the mark
    height = max(mh, baseline + max(b[3], 0))
    mark = place(mark_paths(mark_color, uid), FULL_BOX, 0, 0, mw, mh)
    text = f'<g transform="translate({mw + gap - b[0]:.3f} {baseline:.3f})">{word}</g>'
    width = mw + gap + (b[2] - b[0])
    return mark + text, width, height


# ---- currents (wallpaper, banner, social card) -----------------------------------
def currents(w, h, n, seed, color, alpha, width, focus_y, spread=0.32, amp=(0.006, 0.018)):
    """Faint water currents: n wavy lines across the whole width, brighter near
    focus_y, where the penguin swims."""
    rnd = random.Random(seed)
    out = []
    for i in range(n):
        y0 = -0.05 * h + 1.10 * h * (i + rnd.uniform(0.15, 0.85)) / n
        a = rnd.uniform(*amp) * h
        lam = rnd.uniform(0.32, 0.62) * w
        ph = rnd.uniform(0, 2 * math.pi)
        steps = max(24, int(w / lam * 12))
        pts = []
        for j in range(steps + 1):
            x = -0.02 * w + 1.04 * w * j / steps
            y = y0 + a * math.sin(2 * math.pi * x / lam + ph)
            pts.append(f"{x:.1f} {y:.1f}")
        near = math.exp(-((y0 - focus_y) / (spread * h)) ** 2)
        op = alpha * (0.35 + 0.65 * near) * rnd.uniform(0.7, 1.2)
        out.append(f'<path d="M{" L".join(pts)}" stroke-opacity="{op:.3f}" '
                   f'stroke-width="{width * rnd.uniform(0.8, 1.25):.2f}"/>')
    return (f'<g fill="none" stroke="{color}" stroke-linecap="round" stroke-linejoin="round">'
            f'{"".join(out)}</g>')


# ---- writers -------------------------------------------------------------------
def svg(w, h, body, title=None, vb=None):
    t = f"<title>{title}</title>" if title else ""
    vb = vb or f"0 0 {w:g} {h:g}"
    return (f'<svg {SVG_NS} width="{w:g}" height="{h:g}" viewBox="{vb}">{t}{body}</svg>\n')


def write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def render(svg_path, png_path, width):
    Path(png_path).parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["node", str(SRC / "render.mjs"), str(svg_path), str(png_path), str(width)],
                   check=True, cwd=SRC)


def main():
    out_svg = BRAND / "svg"
    out_png = BRAND / "png"
    art = BRAND / "art"
    bw, bh = box_size(FULL_BOX)
    cw, ch = box_size(COMPACT_BOX)
    mh = 64.0

    # Mark, free-standing (full), and the compact mark for small sizes
    for name, color in [("mark-lime", LIME), ("mark-moss", MOSS), ("mark-ink", INK),
                        ("mark-black", "#000000"), ("mark-white", "#ffffff")]:
        w = round(mh * bw / bh, 2)
        p = write(out_svg / f"{name}.svg",
                  svg(w, mh, place(mark_paths(color), FULL_BOX, 0, 0, w, mh), "AgentUX"))
        if name in ("mark-lime", "mark-ink", "mark-white"):
            for s in (128, 256, 512):
                render(p, out_png / f"{name}-{s}.png", s)
    for name, color in [("mark-compact-lime", LIME), ("mark-compact-moss", MOSS),
                        ("mark-compact-ink", INK), ("mark-compact-white", "#ffffff")]:
        w = round(mh * cw / ch, 2)
        write(out_svg / f"{name}.svg",
              svg(w, mh, place(compact_paths(color), COMPACT_BOX, 0, 0, w, mh), "AgentUX"))

    # App icon: Ink tile, lime penguin
    p = write(out_svg / "icon.svg", svg(64, 64, tile(), "AgentUX"))
    render(p, out_png / "icon-1024.png", 1024)
    for s in (16, 32, 48, 64, 128, 256):
        render(p, out_png / f"icon-{s}.png", s)
    # Small-size tile: full bleed and less padding so 16 px stays readable
    small = (f'<rect width="64" height="64" rx="14" fill="{INK}"/>'
             + place(compact_paths(LIME), COMPACT_BOX, 4, 4, 56, 56))
    p = write(out_svg / "favicon.svg", svg(64, 64, small, "AgentUX"))
    for s in (16, 32):
        render(p, out_png / f"favicon-{s}.png", s)

    # Org avatar: full bleed Ink with the full mark, as in the original art
    av = f'<rect width="64" height="64" fill="{INK}"/>' + place(mark_paths(LIME), FULL_BOX, 5, 5, 54, 54)
    p = write(out_svg / "avatar.svg", svg(64, 64, av, "AgentUX"))
    render(p, out_png / "avatar-512.png", 512)

    # Wordmark
    for name, color in [("wordmark-mist", MIST), ("wordmark-ink", INK),
                        ("wordmark-black", "#000000"), ("wordmark-white", "#ffffff")]:
        body, adv, b, cap = wordmark(100, color)
        w = b[2] - b[0]
        h = b[3] - b[1]
        write(out_svg / f"{name}.svg",
              svg(round(w, 2), round(h, 2), f'<g transform="translate({-b[0]:.3f} {-b[1]:.3f})">{body}</g>',
                  "AgentUX", vb=f"0 0 {w:.2f} {h:.2f}"))

    # Lockups
    lockups = {
        "lockup-dark": (LIME, MIST),     # on Ink / dark backgrounds
        "lockup-light": (MOSS, INK),     # on Paper / light backgrounds
        "lockup-black": ("#000000", "#000000"),
        "lockup-white": ("#ffffff", "#ffffff"),
    }
    for name, (mc, wc) in lockups.items():
        body, w, h = lockup(mc, wc)
        p = write(out_svg / f"{name}.svg", svg(round(w, 2), round(h, 2), body, "AgentUX",
                                                 vb=f"0 0 {w:.2f} {h:.2f}"))
        if name in ("lockup-dark", "lockup-light"):
            render(p, out_png / f"{name}-1200.png", 1200)

    # Social preview 1280 x 640
    write(out_svg / "social.svg", social())
    render(out_svg / "social.svg", out_png / "social-1280x640.png", 1280)

    # Profile banners (also copied into the .github repo)
    for theme in ("dark", "light"):
        p = write(out_svg / f"banner-{theme}.svg", banner(theme))
        render(p, out_png / f"banner-{theme}.png", 1280)

    # Wallpaper key art (the Plasma wallpaper package is rendered from these)
    for theme in ("dark", "light"):
        p = write(art / f"wallpaper-{theme}.svg", wallpaper(theme, 3840, 2160))
        render(p, art / f"wallpaper-{theme}-preview.png", 1280)


def tagline(size, color, wght=400):
    d, adv, b, cap = text_path("The Linux distribution where every coding agent works as one team.",
                               size, wght=wght, wdth=100, tracking=-0.01)
    return f'<path fill="{color}" d="{d}"/>', adv, b


def social():
    W, H = 1280, 640
    field = currents(W, H, 40, 7, MIST, 0.06, 1.4, 470)
    word, adv, b, cap = wordmark(1, MIST)
    word, adv, b, cap = wordmark(58 / cap, MIST)
    tag, tw, tb = tagline(22, SLATE)
    pw = 760
    ph = pw * box_size(FULL_BOX)[1] / box_size(FULL_BOX)[0]
    return svg(W, H,
               f'<rect width="{W}" height="{H}" fill="{INK}"/>{field}'
               + place(mark_paths(LIME, "s"), FULL_BOX, W - pw - 70, 470 - ph / 2, pw, ph)
               + f'<g transform="translate({90 - b[0]:.2f} {92 + cap:.2f})">{word}</g>'
               f'<g transform="translate(92 {92 + cap + 48})">{tag}</g>',
               "AgentUX")


def banner(theme):
    """Profile banner: the penguin swims through the currents towards the wordmark."""
    W, H = 1280, 320
    if theme == "dark":
        bg, base, hi, wc, tc, ba = INK, MIST, LIME, MIST, SLATE, 0.07
    else:
        bg, base, hi, wc, tc, ba = PAPER, INK, MOSS, INK, SLATE_L, 0.09
    jy = 150
    field = currents(W, H, 26, 11, base, ba, 1.2, jy)
    pw = 470
    ph = pw * box_size(FULL_BOX)[1] / box_size(FULL_BOX)[0]
    word, adv, b, cap = wordmark(1, wc)
    size = 64 / cap   # cap height 64 px
    word, adv, b, cap = wordmark(size, wc)
    x = 580
    base_y = jy + cap / 2
    l1, w1, b1 = tagline_text("The Linux distribution where every coding agent", 19, tc)
    l2, w2, b2 = tagline_text("works as one team.", 19, tc)
    return svg(W, H,
               f'<clipPath id="c"><rect width="{W}" height="{H}" rx="16"/></clipPath>'
               f'<g clip-path="url(#c)"><rect width="{W}" height="{H}" fill="{bg}"/>{field}</g>'
               + place(mark_paths(hi, "b"), FULL_BOX, 70, jy - ph / 2 + 8, pw, ph)
               + f'<g transform="translate({x - b[0]:.2f} {base_y:.2f})">{word}</g>'
               f'<g transform="translate({x + 2} {base_y + 62:.2f})">{l1}</g>'
               f'<g transform="translate({x + 2} {base_y + 92:.2f})">{l2}</g>',
               "AgentUX: the Linux distribution where every coding agent works as one team")


def tagline_text(text, size, color, wght=400):
    d, adv, b, cap = text_path(text, size, wght=wght, wdth=100, tracking=-0.01)
    return f'<path fill="{color}" d="{d}"/>', adv, b


def wallpaper(theme, W, H):
    if theme == "dark":
        bg0, bg1, base, hi, ba, ha = "#0e1115", INK, MIST, LIME, 0.05, 0.9
    else:
        bg0, bg1, base, hi, ba, ha = "#f7f8f9", "#eceef1", INK, MOSS, 0.065, 0.9
    px, py = W * 0.60, H * 0.54           # the penguin's centre
    pw = W * 0.40
    ph = pw * box_size(FULL_BOX)[1] / box_size(FULL_BOX)[0]
    field = currents(W, H, 110, 3, base, ba, W / 2600, py)
    return svg(W, H,
               f'<defs><radialGradient id="bg" cx="{px / W:.3f}" cy="{py / H:.3f}" r="0.9">'
               f'<stop offset="0" stop-color="{bg0}"/><stop offset="1" stop-color="{bg1}"/>'
               f'</radialGradient></defs>'
               f'<rect width="{W}" height="{H}" fill="url(#bg)"/>{field}'
               + place(mark_paths(hi, "w"), FULL_BOX, px - pw / 2, py - ph / 2, pw, ph, opacity=ha),
               "AgentUX")


if __name__ == "__main__":
    main()
